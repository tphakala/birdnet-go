import { describe, it, expect, vi } from 'vitest';
import { renderTyped, screen, fireEvent, createI18nMock } from '../../../../test/render-helpers';
import ErrorAlert from './ErrorAlert.svelte';
import ErrorAlertTestWrapper from './ErrorAlert.test.svelte';
import type { ComponentProps } from 'svelte';

// Mock i18n translations using the shared helper
vi.mock('$lib/i18n', () => ({
  t: createI18nMock({
    'common.aria.dismissAlert': 'Dismiss alert',
  }),
}));

// Helper function to render ErrorAlert with proper typing
const renderErrorAlert = (props: Partial<ComponentProps<typeof ErrorAlert>>) => {
  return renderTyped(ErrorAlert, { props });
};

// Click counts: a click generated by Enter or Space on a button reports none,
// a real mouse click reports at least one
const KEYBOARD_CLICK_DETAIL = 0;
const MOUSE_CLICK_DETAIL = 1;

describe('ErrorAlert', () => {
  it('renders with default props', () => {
    renderErrorAlert({ message: 'An error occurred' });

    const alert = screen.getByRole('alert');
    expect(alert).toBeInTheDocument();
    // Now uses native Tailwind classes with CSS variables
    expect(alert.className).toContain('bg-[color-mix(in_srgb,var(--color-error)');
    expect(screen.getByText('An error occurred')).toBeInTheDocument();
  });

  it('renders different alert types', () => {
    const types = ['error', 'warning', 'info', 'success'] as const;

    types.forEach(type => {
      const { unmount } = renderErrorAlert({
        message: `${type} message`,
        type,
      });

      const alert = screen.getByRole('alert');
      // Check for type-specific CSS variable class
      expect(alert.className).toContain(`bg-[color-mix(in_srgb,var(--color-${type})`);

      unmount();
    });
  });

  it('renders with custom children', () => {
    renderTyped(ErrorAlertTestWrapper, {
      props: {
        showChildren: true,
      },
    });

    expect(screen.getByText('Custom error content')).toBeInTheDocument();
    expect(screen.getByText('With a link')).toBeInTheDocument();
  });

  it('shows dismiss button when dismissible', () => {
    renderErrorAlert({
      message: 'Dismissible alert',
      dismissible: true,
    });

    const dismissButton = screen.getByLabelText('Dismiss alert');
    expect(dismissButton).toBeInTheDocument();
  });

  it('calls onDismiss and hides alert when dismissed', async () => {
    const onDismiss = vi.fn();

    renderErrorAlert({
      message: 'Dismissible alert',
      dismissible: true,
      onDismiss,
    });

    const dismissButton = screen.getByLabelText('Dismiss alert');
    await fireEvent.click(dismissButton);

    expect(onDismiss).toHaveBeenCalledTimes(1);
    expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  });

  it('returns focus to where it came from when dismissed from the keyboard', async () => {
    const outside = document.createElement('button');
    outside.textContent = 'Save';
    document.body.appendChild(outside);

    try {
      renderTyped(ErrorAlertTestWrapper, {
        props: { dismissible: true, showChildren: true },
      });

      const link = screen.getByText('With a link');
      const dismissButton = screen.getByLabelText('Dismiss alert');

      // Tab order: the outside button, then the link in the alert, then the
      // dismiss button. Focus returns to where it entered the alert from, not to
      // the link, which is removed together with the alert.
      outside.focus();
      link.focus();
      dismissButton.focus();
      expect(document.activeElement).toBe(dismissButton);

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(document.activeElement).toBe(outside);
    } finally {
      outside.remove();
    }
  });

  it('does not move focus when focus entered from no element and nothing was remembered', async () => {
    const outside = document.createElement('button');
    document.body.appendChild(outside);

    try {
      renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true } });
      const dismissButton = screen.getByLabelText('Dismiss alert');

      // Nothing outside the alert had focus, so there is no related element
      dismissButton.focus();

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(document.activeElement).not.toBe(outside);
    } finally {
      outside.remove();
    }
  });

  it('keeps the return target when the window regains focus inside the alert', async () => {
    const outside = document.createElement('button');
    document.body.appendChild(outside);

    try {
      renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true } });
      const dismissButton = screen.getByLabelText('Dismiss alert');

      outside.focus();
      dismissButton.focus();
      // The window regaining focus fires focusin on the focused control with no related element
      await fireEvent.focusIn(dismissButton, { relatedTarget: null });

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(document.activeElement).toBe(outside);
    } finally {
      outside.remove();
    }
  });

  it('forgets the return target when focus leaves the alert for the page body', async () => {
    const outside = document.createElement('button');
    document.body.appendChild(outside);
    const hasFocusSpy = vi.spyOn(document, 'hasFocus').mockReturnValue(true);

    try {
      renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true } });
      const dismissButton = screen.getByLabelText('Dismiss alert');

      outside.focus();
      dismissButton.focus();
      // A click on plain page content: focus goes to the body while the window keeps focus
      await fireEvent.focusOut(dismissButton, { relatedTarget: null });
      // Later Tab back into the alert, with no related element
      await fireEvent.focusIn(dismissButton, { relatedTarget: null });

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(document.activeElement).not.toBe(outside);
    } finally {
      hasFocusSpy.mockRestore();
      outside.remove();
    }
  });

  it('keeps the return target when the whole window loses focus', async () => {
    const outside = document.createElement('button');
    document.body.appendChild(outside);
    const hasFocusSpy = vi.spyOn(document, 'hasFocus').mockReturnValue(false);

    try {
      renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true } });
      const dismissButton = screen.getByLabelText('Dismiss alert');

      outside.focus();
      dismissButton.focus();
      // A window blur fires focusout with no related element, and the document has lost focus
      await fireEvent.focusOut(dismissButton, { relatedTarget: null });
      await fireEvent.focusIn(dismissButton, { relatedTarget: null });

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(document.activeElement).toBe(outside);
    } finally {
      hasFocusSpy.mockRestore();
      outside.remove();
    }
  });

  it('still calls a caller supplied onfocusout handler', async () => {
    const onfocusout = vi.fn();
    renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true, onfocusout } });

    const dismissButton = screen.getByLabelText('Dismiss alert');
    dismissButton.focus();
    await fireEvent.focusOut(dismissButton, { relatedTarget: null });

    expect(onfocusout).toHaveBeenCalledTimes(1);
  });

  it('does not move focus when dismissed with the mouse', async () => {
    const outside = document.createElement('button');
    document.body.appendChild(outside);

    try {
      renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true } });
      const dismissButton = screen.getByLabelText('Dismiss alert');

      outside.focus();
      dismissButton.focus();

      await fireEvent.click(dismissButton, { detail: MOUSE_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(document.activeElement).not.toBe(outside);
    } finally {
      outside.remove();
    }
  });

  it('does not steal focus when it has moved outside the alert before dismissing', async () => {
    const outside = document.createElement('button');
    const elsewhere = document.createElement('button');
    document.body.append(outside, elsewhere);

    try {
      renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true } });
      const dismissButton = screen.getByLabelText('Dismiss alert');

      outside.focus();
      dismissButton.focus();
      elsewhere.focus();

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(document.activeElement).toBe(elsewhere);
    } finally {
      outside.remove();
      elsewhere.remove();
    }
  });

  it('does not throw or force focus when the return target was removed', async () => {
    const outside = document.createElement('button');
    document.body.appendChild(outside);
    const focusSpy = vi.spyOn(outside, 'focus');

    try {
      renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true } });
      const dismissButton = screen.getByLabelText('Dismiss alert');

      outside.focus();
      dismissButton.focus();
      focusSpy.mockClear();
      outside.remove();

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('alert')).not.toBeInTheDocument();
      expect(focusSpy).not.toHaveBeenCalled();
      expect(document.activeElement).toBe(document.body);
    } finally {
      outside.remove();
    }
  });

  it('still calls a caller supplied onfocusin handler', async () => {
    const onfocusin = vi.fn();
    renderTyped(ErrorAlertTestWrapper, { props: { dismissible: true, onfocusin } });

    screen.getByLabelText('Dismiss alert').focus();

    expect(onfocusin).toHaveBeenCalledTimes(1);
  });

  it('renders with custom className', () => {
    renderErrorAlert({
      message: 'Custom class alert',
      className: 'custom-alert-class',
    });

    const alert = screen.getByRole('alert');
    expect(alert).toHaveClass('custom-alert-class');
  });

  it('spreads additional props', () => {
    renderErrorAlert({
      message: 'Alert with id',
      id: 'test-alert',
      'data-testid': 'error-alert',
    });

    const alert = screen.getByRole('alert');
    expect(alert).toHaveAttribute('id', 'test-alert');
    expect(alert).toHaveAttribute('data-testid', 'error-alert');
  });
});
