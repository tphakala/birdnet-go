/**
 * Tests for the dashboard legacy database banner.
 *
 * The banner renders only for the four legacy notice kinds the migration
 * status endpoint reports. "none", unknown kinds, a failed fetch and guests
 * render nothing, and guests never call the endpoint (a guest fetch would
 * redirect to the login page in private mode). A dismissal holds for the
 * session until the notice kind changes, is checked against a fresh fetch on
 * every mount, and must work when sessionStorage throws.
 */
import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';
import { cleanup, fireEvent, screen, waitFor } from '@testing-library/svelte';
import { tick } from 'svelte';
import { renderTyped } from '../../../../../test/render-helpers';

const { apiGet, isGuestMode, handleAppLinkClick } = vi.hoisted(() => ({
  apiGet: vi.fn<(url: string) => Promise<unknown>>(),
  isGuestMode: vi.fn<() => boolean>(() => false),
  // Prevents the anchor's default navigation, as the real handler does for in-app links.
  handleAppLinkClick: vi.fn<(event: Event) => void>(event => event.preventDefault()),
}));

vi.mock('$lib/utils/api', () => ({
  api: { get: apiGet },
}));

vi.mock('$lib/stores/appState.svelte', () => ({
  isGuestMode,
}));

vi.mock('$lib/stores/navigation.svelte', () => ({
  handleAppLinkClick,
}));

import LegacyDatabaseBanner from './LegacyDatabaseBanner.svelte';
import { resetBasePath, setBasePath } from '$lib/utils/urlHelpers';

const STATUS_URL = '/api/v2/system/database/migration/status';
const DISMISS_KEY = 'birdnet.legacyDbBannerDismissed';
// A deployment prefix such as a reverse proxy or Home Assistant ingress adds.
const BASE_PATH = '/proxy/birdnet';
// Click counts: a click generated by Enter or Space on a button reports none,
// a real mouse click reports at least one.
const KEYBOARD_CLICK_DETAIL = 0;
const MOUSE_CLICK_DETAIL = 1;

/** Lets the mount fetch settle and the banner render. */
async function settle(): Promise<void> {
  await tick();
  await Promise.resolve();
  await tick();
}

function respondWith(kind: string | undefined): void {
  apiGet.mockResolvedValue({ state: 'idle', legacy_notice: kind });
}

describe('LegacyDatabaseBanner', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    apiGet.mockReset();
    isGuestMode.mockReturnValue(false);
    sessionStorage.clear();
    setBasePath(BASE_PATH);
  });

  afterEach(() => {
    cleanup();
    sessionStorage.clear();
    resetBasePath();
  });

  it.each([
    ['not_started', 'status', 'legacyNotStarted'],
    ['in_progress', 'status', 'legacyInProgress'],
    ['restart_required', 'status', 'legacyRestartRequired'],
    ['needs_attention', 'alert', 'legacyNeedsAttention'],
  ])('shows the %s notice as a %s with a database link', async (kind, role, keyStem) => {
    respondWith(kind);
    renderTyped(LegacyDatabaseBanner, { props: { class: 'mb-6' } });

    const banner = await screen.findByRole(role);
    expect(apiGet).toHaveBeenCalledWith(STATUS_URL);
    expect(banner).toHaveTextContent(`notifications.content.migration.${keyStem}Title`);
    expect(banner).toHaveTextContent(`notifications.content.migration.${keyStem}Message`);
    expect(banner).toHaveClass('mb-6');

    const link = screen.getByRole('link', { name: 'dashboard.legacyDatabase.action' });
    expect(link).toHaveAttribute('href', `${BASE_PATH}/ui/system/database`);
    await fireEvent.click(link);
    expect(handleAppLinkClick).toHaveBeenCalledTimes(1);
    expect(screen.getByRole('button', { name: 'common.aria.dismissAlert' })).toBeInTheDocument();
  });

  it.each([
    ['none', 'none'],
    ['an unknown kind', 'migrating_soon'],
    ['a missing field', undefined],
  ])('renders nothing for %s', async (_label, kind) => {
    respondWith(kind);
    const { container } = renderTyped(LegacyDatabaseBanner);
    await settle();

    expect(apiGet).toHaveBeenCalledTimes(1);
    expect(container.textContent.trim()).toBe('');
  });

  it('renders nothing when the fetch fails', async () => {
    apiGet.mockRejectedValue(new Error('Service Unavailable'));
    const { container } = renderTyped(LegacyDatabaseBanner);
    await settle();

    expect(apiGet).toHaveBeenCalledTimes(1);
    expect(container.textContent.trim()).toBe('');
  });

  it('never fetches or renders for a guest', async () => {
    isGuestMode.mockReturnValue(true);
    respondWith('not_started');
    const { container } = renderTyped(LegacyDatabaseBanner);
    await settle();

    expect(apiGet).not.toHaveBeenCalled();
    expect(container.textContent.trim()).toBe('');
  });

  it('keeps a dismissed kind hidden across remounts and shows the banner again when the kind changes', async () => {
    const dismissButton = (): Promise<HTMLElement> =>
      screen.findByRole('button', { name: 'common.aria.dismissAlert' });

    respondWith('not_started');
    const first = renderTyped(LegacyDatabaseBanner);
    await fireEvent.click(await dismissButton());
    await waitFor(() => expect(screen.queryByRole('status')).toBeNull());
    expect(sessionStorage.getItem(DISMISS_KEY)).toBe('not_started');
    first.unmount();

    // Same kind after a remount: the status is fetched, the banner stays hidden.
    apiGet.mockClear();
    const second = renderTyped(LegacyDatabaseBanner);
    await settle();
    expect(apiGet).toHaveBeenCalledTimes(1);
    expect(second.container.textContent.trim()).toBe('');
    second.unmount();

    // A different kind (the migration failed) shows the banner again.
    respondWith('needs_attention');
    const third = renderTyped(LegacyDatabaseBanner);
    await fireEvent.click(await dismissButton());
    await waitFor(() => expect(screen.queryByRole('alert')).toBeNull());
    expect(sessionStorage.getItem(DISMISS_KEY)).toBe('needs_attention');
    third.unmount();

    // Dismissing one kind does not hide the first kind when it returns.
    respondWith('not_started');
    renderTyped(LegacyDatabaseBanner);
    expect(await screen.findByRole('status')).toHaveTextContent(
      'notifications.content.migration.legacyNotStartedTitle'
    );
  });

  it('returns focus to where it came from when dismissed from the keyboard', async () => {
    const outside = document.createElement('button');
    outside.textContent = 'Previous control';
    document.body.appendChild(outside);

    try {
      respondWith('not_started');
      renderTyped(LegacyDatabaseBanner);
      const link = await screen.findByRole('link', { name: 'dashboard.legacyDatabase.action' });
      const dismissButton = screen.getByRole('button', { name: 'common.aria.dismissAlert' });

      // Tab order: the control before the banner, the database link, the dismiss
      // button. Focus returns to where it entered the banner from, not to the link,
      // which is removed together with the banner.
      outside.focus();
      link.focus();
      dismissButton.focus();
      expect(document.activeElement).toBe(dismissButton);

      await fireEvent.click(dismissButton, { detail: KEYBOARD_CLICK_DETAIL });

      expect(screen.queryByRole('status')).toBeNull();
      expect(document.activeElement).toBe(outside);
    } finally {
      outside.remove();
    }
  });

  it('leaves focus alone when dismissed with the mouse', async () => {
    const outside = document.createElement('button');
    document.body.appendChild(outside);

    try {
      respondWith('not_started');
      renderTyped(LegacyDatabaseBanner);
      const dismissButton = await screen.findByRole('button', {
        name: 'common.aria.dismissAlert',
      });

      outside.focus();
      dismissButton.focus();
      await fireEvent.click(dismissButton, { detail: MOUSE_CLICK_DETAIL });

      expect(screen.queryByRole('status')).toBeNull();
      expect(document.activeElement).toBe(document.body);
    } finally {
      outside.remove();
    }
  });

  it('shows the banner for a flag stored by an earlier build', async () => {
    sessionStorage.setItem(DISMISS_KEY, '1');
    respondWith('not_started');
    renderTyped(LegacyDatabaseBanner);

    expect(await screen.findByRole('status')).toBeInTheDocument();
  });

  it('still hides on dismiss when sessionStorage throws', async () => {
    const blocked = (): never => {
      throw new DOMException('blocked', 'SecurityError');
    };
    const getItem = vi.spyOn(Storage.prototype, 'getItem').mockImplementation(blocked);
    const setItem = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(blocked);
    try {
      respondWith('needs_attention');
      renderTyped(LegacyDatabaseBanner);

      await fireEvent.click(
        await screen.findByRole('button', { name: 'common.aria.dismissAlert' })
      );
      await waitFor(() => expect(screen.queryByRole('alert')).toBeNull());
      expect(setItem).toHaveBeenCalled();
    } finally {
      getItem.mockRestore();
      setItem.mockRestore();
    }
  });
});
